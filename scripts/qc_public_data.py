"""Quality-control report for Dataset B; writes docs/dataset_b_qc.md."""
import csv
import statistics
from collections import Counter
from itertools import combinations
from pathlib import Path

from Bio import SeqIO
from Bio.Seq import Seq

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "public_genomic"


def hamming(a, b):
    # deliberately not imported from genomath, so QC numbers stay an independent oracle for the tests
    return sum(x != y for x, y in zip(a, b))


def main():
    with (DATA / "h3n2_ha_cds.fasta").open(encoding="utf-8") as fh:
        recs = list(SeqIO.parse(fh, "fasta"))
    with (DATA / "accessions.csv").open(encoding="utf-8") as fh:
        meta = {r["accession"]: r for r in csv.DictReader(fh)}
    seqs = {r.id: str(r.seq) for r in recs}
    out = ["# Dataset B quality-control report", "",
           "Generated by `scripts/qc_public_data.py` from `data/public_genomic/h3n2_ha_cds.fasta`. Raw observations only.", ""]

    lengths = Counter(len(s) for s in seqs.values())
    out += ["## Records", f"- sequences: {len(seqs)}", f"- length distribution: {dict(lengths)}",
            f"- collection months: {dict(sorted(Counter(m['collection_date'][-8:] for m in meta.values()).items()))}",
            f"- countries: {dict(Counter(m['country'] for m in meta.values()).most_common())}", ""]

    out += ["## Alphabet"]
    bad = {k: {c: n for c, n in Counter(s).items() if c not in "ACGT"} for k, s in seqs.items()}
    bad = {k: v for k, v in bad.items() if v}
    out.append(f"- sequences containing any non-ACGT character: {len(bad)}")
    for k, v in bad.items():
        out.append(f"  - {k}: {v} (will be dropped and logged by the Stage 1 preprocessing rule)")
    out.append("")

    out += ["## Coding-frame sanity (Biopython translation, standard code)"]
    issues = []
    for k, s in seqs.items():
        if set(s) - set("ACGT"):
            continue
        p = str(Seq(s).translate())
        if not s.startswith("ATG") or not p.endswith("*") or "*" in p[:-1]:
            issues.append(k)
    out += [f"- clean sequences checked: {len(seqs) - len(bad)}; start ATG, single terminal stop, no internal stop: "
            f"{len(seqs) - len(bad) - len(issues)}; failing: {issues or 'none'}", ""]

    clean = {k: s for k, s in seqs.items() if k not in bad}
    groups = {}
    for k, s in clean.items():
        groups.setdefault(s, []).append(k)
    dups = [g for g in groups.values() if len(g) > 1]
    out += ["## Duplicates (among ACGT-only sequences)", f"- haplotypes: {len(groups)} from {len(clean)} sequences",
            f"- groups of identical sequences: {dups or 'none'}", ""]

    haps = list(groups)
    d = [hamming(a, b) for a, b in combinations(haps, 2)]
    hist = Counter(d)
    n = len(haps[0]) if haps else 0
    out += ["## Pairwise Hamming distance between haplotypes",
            f"- pairs: {len(d)}",
            f"- min / median / mean / max: {min(d)} / {statistics.median(d)} / {statistics.mean(d):.2f} / {max(d)}",
            f"- max as a fraction of length: {max(d) / n:.4f} (a misaligned pair would be near 0.75)",
            f"- number of d_H = 1 edges: {hist.get(1, 0)}",
            f"- distance histogram (d: pairs): {dict(sorted(hist.items()))}", ""]
    cum = 0
    out += ["| k | edges with d_H <= k |", "|---|---|"]
    for k in sorted(hist):
        cum += hist[k]
        if k <= 10 or k == max(d):
            out.append(f"| {k} | {cum} |")
    text = "\n".join(out) + "\n"
    (ROOT / "docs" / "dataset_b_qc.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
